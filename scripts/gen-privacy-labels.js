#!/usr/bin/env node
/**
 * Apple App Privacy ("nutrition label") + Google Play Data safety answers from server-lib/data-inventory.js.
 *   node scripts/gen-privacy-labels.js           write docs/store/privacy-labels.v<N>.{json,md}
 *   node scripts/gen-privacy-labels.js --check   exit 1 when the docs are stale (used by test-global-l9)
 * DRAFT — requires legal / store-policy review before submission.
 */
'use strict';

const fs = require('fs');
const path = require('path');
const INV = require('../server-lib/data-inventory');

const ROOT = path.join(__dirname, '..');

function build() {
  const items = INV.inventory();
  const apple = {};
  items.forEach((d) => {
    const key = d.apple.category;
    apple[key] = apple[key] || { linkedToYou: [], notLinked: [], usedForTracking: [] };
    (d.linked ? apple[key].linkedToYou : apple[key].notLinked).push({
      type: d.apple.type,
      purposes: [...new Set(d.purposes.map((p) => INV.PURPOSE_LABELS[p][0]))],
    });
  });
  const google = items.map((d) => ({
    category: d.google.category,
    type: d.google.type,
    collected: true,
    shared: d.shared,
    optional: d.optional,
    ephemeral: false,
    purposes: [...new Set(d.purposes.map((p) => INV.PURPOSE_LABELS[p][1]))],
  }));
  return {
    version: INV.VERSION,
    status: 'DRAFT — requires legal review',
    facts: INV.FACTS,
    apple: { dataUsedToTrackYou: [], categories: apple },
    google: {
      dataCollected: google,
      dataShared: [],
      securityPractices: { encryptedInTransit: INV.FACTS.encryptedInTransit, deletionRequest: true, deletionUrl: INV.FACTS.deletionRequest.web },
    },
  };
}

function markdown(doc) {
  const lines = [
    `# Store privacy labels — v${doc.version}`,
    '',
    `> ${doc.status}. Generated by \`scripts/gen-privacy-labels.js\` from \`server-lib/data-inventory.js\` — do not edit by hand.`,
    '',
    `- Tracking (Apple): **${doc.facts.tracking ? 'Yes' : 'No'}** · Sells data: **${doc.facts.sellsData ? 'Yes' : 'No'}** · Third-party ads: **${doc.facts.thirdPartyAdvertising ? 'Yes' : 'No'}**`,
    `- Encrypted in transit: **${doc.facts.encryptedInTransit ? 'Yes' : 'No'}** · Deletion: in app + web (\`${doc.facts.deletionRequest.web}\`)`,
    '',
    '## Apple — App Privacy',
    '',
    '| Category | Data type | Linked | Purposes |',
    '|---|---|---|---|',
  ];
  Object.keys(doc.apple.categories)
    .sort()
    .forEach((cat) => {
      const c = doc.apple.categories[cat];
      c.linkedToYou.forEach((x) => lines.push(`| ${cat} | ${x.type} | Yes | ${x.purposes.join(', ')} |`));
      c.notLinked.forEach((x) => lines.push(`| ${cat} | ${x.type} | No | ${x.purposes.join(', ')} |`));
    });
  lines.push('', '## Google Play — Data safety', '', '| Category | Data type | Shared | Optional | Purposes |', '|---|---|---|---|---|');
  doc.google.dataCollected.forEach((d) => lines.push(`| ${d.category} | ${d.type} | ${d.shared ? 'Yes' : 'No'} | ${d.optional ? 'Yes' : 'No'} | ${d.purposes.join(', ')} |`));
  lines.push('', 'Data shared: none (service providers acting on our behalf are processors, not sharing, under both stores’ definitions).', '');
  return lines.join('\n');
}

function files() {
  const doc = build();
  const base = path.join(ROOT, 'docs', 'store', `privacy-labels.v${doc.version}`);
  return { [base + '.json']: JSON.stringify(doc, null, 2) + '\n', [base + '.md']: markdown(doc) };
}

if (require.main === module) {
  const check = process.argv.includes('--check');
  const out = files();
  let stale = 0;
  Object.keys(out).forEach((f) => {
    if (check) {
      if (!fs.existsSync(f) || fs.readFileSync(f, 'utf8').replace(/\r\n/g, '\n') !== out[f]) stale++;
    } else {
      fs.mkdirSync(path.dirname(f), { recursive: true });
      fs.writeFileSync(f, out[f]);
    }
  });
  if (check && stale) {
    console.error('privacy labels are stale — run node scripts/gen-privacy-labels.js');
    process.exit(1);
  }
  console.log(check ? 'privacy labels up to date' : 'wrote ' + Object.keys(out).map((f) => path.relative(ROOT, f)).join(', '));
}

module.exports = { build, markdown, files };
