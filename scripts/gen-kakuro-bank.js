#!/usr/bin/env node
/**
 * Kakuro puzzle bank builder (Dangal P14).
 *
 *   node scripts/gen-kakuro-bank.js            → public/src/js/games/data/kakuro-bank.js
 *
 * Numbered puzzles per difficulty come from KakuroCore.generate(diff, puzzleSeed(diff, n)); Daily
 * puzzles come from generate(dailyDifficulty(day), SoloCore.dailySeed('ankjod', day)) for DAILY_DAYS
 * days from DAILY_START. Every entry is re-checked for exactly one solution and its grade before it
 * is written. Progress is cached in scripts/data/kakuro-bank.json so a long run can resume.
 */
'use strict';

const fs = require('fs');
const path = require('path');
const SoloCore = require('../public/src/js/games/solo-core.js');
const K = require('../public/src/js/games/kakuro-core.js');

const COUNTS = { easy: 100, medium: 100, hard: 80, expert: 40 };
const DAILY_START = SoloCore.dayNoFromKey('2026-09-01');
const DAILY_DAYS = 500;
const CACHE = path.join(__dirname, 'data/kakuro-bank.json');
const OUT = path.join(__dirname, '../public/src/js/games/data/kakuro-bank.js');

function load() {
  try {
    return JSON.parse(fs.readFileSync(CACHE, 'utf8'));
  } catch (e) {
    return { easy: [], medium: [], hard: [], expert: [], daily: [] };
  }
}
function save(b) {
  fs.mkdirSync(path.dirname(CACHE), { recursive: true });
  fs.writeFileSync(CACHE, JSON.stringify(b));
}

function make(diff, seed) {
  for (let salt = 0; salt < 6; salt++) {
    const s = salt ? SoloCore.fnv(seed + ':' + salt) : seed;
    const p = K.generate(diff, s, { maxAttempts: 4000 });
    if (!p) continue;
    const g = K.fromRows(p.rows);
    if (K.countSolutions(g, 2, 2000000).count !== 1 || K.gradeOf(g) !== K.GRADE[diff]) continue;
    return p.rows.join('/');
  }
  throw new Error('could not generate ' + diff + ' ' + seed);
}

function writeOut(b) {
  const data = {
    v: 1,
    dailyStart: DAILY_START,
    easy: b.easy,
    medium: b.medium,
    hard: b.hard,
    expert: b.expert,
    daily: b.daily,
  };
  const header =
    '/**\n * Kakuro puzzle bank (Dangal P14) — GENERATED by scripts/gen-kakuro-bank.js; do not hand-edit.\n' +
    ' * Each entry is puzzle rows joined by "/" (# block · X clue · digit = solution). Every puzzle has exactly\n' +
    ' * one solution and the grade of its difficulty. daily[k] is the Daily for day number dailyStart + k,\n' +
    ' * stored as "difficulty:rows".\n */\n';
  const body =
    "(function (root, factory) {\n  const api = factory();\n  if (typeof module === 'object' && module.exports) module.exports = api;\n  else root.KakuroBank = api;\n})(typeof self !== 'undefined' ? self : this, function () {\n  'use strict';\n  return " +
    JSON.stringify(data) +
    ';\n});\n';
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, header + body);
}

function main() {
  const only = process.argv[2] || 'all';
  const b = load();
  const t0 = Date.now();
  Object.keys(COUNTS).forEach((diff) => {
    if (only !== 'all' && only !== diff) return;
    while (b[diff].length < COUNTS[diff]) {
      const n = b[diff].length + 1;
      b[diff].push(make(diff, K.puzzleSeed(diff, n)));
      save(b);
      if (n % 10 === 0) console.log(`${diff} ${n}/${COUNTS[diff]} (${Math.round((Date.now() - t0) / 1000)} s)`);
    }
  });
  if (only === 'all' || only === 'daily') {
    while (b.daily.length < DAILY_DAYS) {
      const day = DAILY_START + b.daily.length;
      const diff = K.dailyDifficulty(day);
      b.daily.push(diff + ':' + make(diff, SoloCore.dailySeed('ankjod', day)));
      save(b);
      if (b.daily.length % 25 === 0) console.log(`daily ${b.daily.length}/${DAILY_DAYS} (${Math.round((Date.now() - t0) / 1000)} s)`);
    }
  }
  writeOut(b);
  console.log('Kakuro bank written', Object.keys(COUNTS).map((d) => d + ' ' + b[d].length).join(', '), 'daily', b.daily.length, Math.round((Date.now() - t0) / 1000) + ' s');
}

if (require.main === module) main();
module.exports = { COUNTS, DAILY_START, DAILY_DAYS };
